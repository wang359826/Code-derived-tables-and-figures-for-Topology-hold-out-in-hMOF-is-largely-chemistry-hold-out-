#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""make_md5sums.py — regenerate outputs/MD5SUMS.txt from the actual archive.

Until 2026-10-14 the manifest was produced ad hoc and drifted: it claimed to cover
"EVERY file in outputs/" while missing 18 of them (including
`leakage_results_chemistry.csv` and `group_stats_chemistry.csv`, which main-text
Table 7 names as its source, and `null_elite_permutation_row.csv`, which SI §S3
names), and one listed entry (`arm_e_partner_coverage.csv`) recorded a hash and a
byte count that no longer matched the file. Running this script makes the manifest
a function of the archive instead of a claim about it.

Usage
-----
    python scripts/make_md5sums.py            # writes outputs/MD5SUMS.txt
    python scripts/make_md5sums.py --check    # exit 1 if the manifest is stale

Excluded on purpose: MD5SUMS.txt itself, __pycache__/, *.pyc, and .DS_Store /
Thumbs.db. Paths are written with forward slashes so the manifest is portable.
"""
from __future__ import annotations

import argparse
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "outputs")

SKIP_DIRS = {"__pycache__"}
SKIP_NAMES = {"MD5SUMS.txt", ".DS_Store", "Thumbs.db"}
SKIP_EXT = {".pyc"}

HEADER = [
    "# outputs archive - MD5 manifest",
    "# generated by scripts/make_md5sums.py -- regenerate it, do not hand-edit.",
    "# Covers every file in outputs/ except this manifest, __pycache__/ and *.pyc.",
    "# Verify from the package root with:  python scripts/make_md5sums.py --check",
    "# MD5  bytes  relative-path",
]


def digest(path: str) -> str:
    h = hashlib.md5()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def collect(outdir: str) -> list[tuple[str, int, str]]:
    rows = []
    for root, dirs, files in os.walk(outdir):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for name in sorted(files):
            if name in SKIP_NAMES or os.path.splitext(name)[1] in SKIP_EXT:
                continue
            full = os.path.join(root, name)
            rel = os.path.relpath(full, outdir).replace(os.sep, "/")
            rows.append((digest(full), os.path.getsize(full), rel))
    rows.sort(key=lambda r: r[2])
    return rows


def render(rows: list[tuple[str, int, str]]) -> str:
    body = "\n".join("%s  %d  %s" % r for r in rows)
    return "\n".join(HEADER) + "\n" + body + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--outdir", default=OUT)
    ap.add_argument("--check", action="store_true",
                    help="只校验：清单与存档不一致时以非零码退出")
    args = ap.parse_args()

    target = os.path.join(args.outdir, "MD5SUMS.txt")
    rows = collect(args.outdir)
    text = render(rows)

    if args.check:
        if not os.path.exists(target):
            print("FAIL: %s 不存在" % target)
            return 1
        have = open(target, encoding="utf-8").read()
        if have.strip() != text.strip():
            print("FAIL: MD5SUMS.txt 与 outputs/ 不一致（跑 make_md5sums.py 重建）")
            return 1
        print("OK: MD5SUMS.txt 覆盖 %d 个文件，且全部匹配" % len(rows))
        return 0

    with open(target, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s\n  %d files covered" % (target, len(rows)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
